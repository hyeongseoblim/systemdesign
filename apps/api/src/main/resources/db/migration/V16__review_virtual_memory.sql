SET content_md = $vm_review$## 1. 주소 공간·주소 변환·실제 메모리를 구분한다

가상 주소는 프로세스가 사용하는 주소 체계다. 페이지 테이블은 접근 권한과 물리 페이지 등의 매핑 정보를 관리하며 TLB는 주소 변환 결과의 캐시다. 같은 숫자의 가상 주소라도 프로세스별로 다른 물리 페이지를 가리킬 수 있다. 공유 매핑처럼 의도적으로 같은 페이지를 참조하는 경우도 있다.

TLB miss는 변환 캐시에 정보가 없다는 뜻으로, 페이지 테이블을 통해 해결될 수 있다. 반드시 Page Fault나 저장 장치 접근을 뜻하지 않는다. Page Fault에는 아직 적재하지 않은 페이지, 쓰기 시 복사, 접근 권한 위반 등 다른 원인이 있다. 커널이 해결할 수 없는 접근은 프로세스에 오류 신호로 전달될 수 있다.

```mermaid
flowchart TD
    A[가상 주소 접근] --> T{TLB에 유효 변환 존재}
    T -->|예| P[권한에 맞는 메모리 접근]
    T -->|아니오| W[페이지 테이블 확인]
    W -->|유효 매핑| P
    W -->|Fault| F{원인과 매핑 확인}
    F --> R[적재·할당·쓰기 복사]
    F --> E[잘못된 접근 오류]
    R --> P
```

가상 주소 공간은 실제 RAM보다 클 수 있지만 무한한 작업 메모리를 보장하지 않는다. 매핑·할당 정책, 실제 접근한 작업 집합, RAM·Swap·컨테이너 제한에 따라 실패나 회수가 발생한다. mmap 성공과 전체 영역을 동시에 물리 메모리에 유지할 수 있다는 보장은 다르다.

## 2. mmap 첫 접근은 무엇을 기다리는가

일반적인 Linux 파일 매핑은 Page Cache와 연결된다. 매핑을 만든 시점과 파일 데이터를 실제로 접근하는 시점이 다를 수 있다. 이미 다른 프로세스가 파일을 읽어 캐시에 올려 두었다면 이 프로세스의 첫 접근도 저장 장치 읽기 없이 해결될 수 있다.

| 상황 | 가능성 | 확인 |
|---|---|---|
| 파일 페이지가 캐시에 있음 | 매핑을 연결하는 Minor Fault 등 | Fault 차이·상주 페이지·접근 시간 |
| 필요한 파일 페이지가 메모리에 없음 | 적재를 위한 Major Fault | 저장 장치 지연·읽기량·경합 |
| 이후 접근 | 페이지·변환·CPU 캐시 재사용 | 회수 여부·작업 집합·접근 순서 |
| 메모리 압박 후 재접근 | 다시 Fault와 적재 가능 | 회수·Swap·메모리 제한 |

Major/Minor는 Fault를 해결할 때 I/O가 필요한지를 구분하는 지표다. 횟수를 디스크 요청 수나 읽은 바이트와 일대일 대응시키지 않는다. Read-ahead는 이후 접근을 미리 준비할 수 있고, TLB·CPU 캐시도 시간에 영향을 준다. “첫 번째는 느리고 두 번째는 반드시 빠르다”는 보장은 없다.

> **성능 함정**
>
> mmap과 read를 비교할 때 Cold/Warm Cache, 파일 크기, 순차/랜덤 접근, 동시 프로세스 수를 맞춘다. 전체 파일을 읽는 경우와 일부 페이지만 접근하는 경우를 같은 작업량이라고 취급하지 않는다. 평균만 보지 말고 Fault로 인한 꼬리 지연도 측정한다.

## 3. 파일 매핑의 공유와 내구성은 다른 축이다

MAP_PRIVATE의 수정은 해당 프로세스의 사본에 반영되며 원본 파일 갱신 방식이 아니다. MAP_SHARED는 파일을 공유하는 매핑에 변경을 반영할 수 있지만, 쓰기가 보인다는 사실과 영구 저장 완료는 별개다. 여러 Writer의 업무 연산이나 자료구조를 원자적으로 만들어주지도 않는다.

동기화가 필요한 공유 매핑은 msync 등의 호출 계약과 오류를 확인한다. 파일·디렉터리 변경까지 포함한 영속화 요구는 파일 시스템과 저장 장치의 보장 범위까지 검토한다. 프로세스 종료·munmap만으로 요구한 장애 시점의 내구성을 증명하지 않는다.

파일 크기가 외부에서 줄어들면 기존 매핑 범위를 접근하다 SIGBUS가 발생할 수 있다. 따라서 파일이 계속 같은 길이로 유지된다는 가정이나 버전 교체·접근 동기화 규약이 필요하다. 매핑의 수명과 원래 FD의 수명도 다르며 FD를 닫았다고 매핑 자체가 즉시 사라지는 것은 아니다.

## 4. Private 사본과 파일 변경을 작게 비교한다

아래 Python 예제는 임시 파일의 매핑 의미를 비교한다. ACCESS_COPY는 사본 변경, ACCESS_WRITE는 파일에 반영할 쓰기 매핑이다. 이 예제로 전원 장애 내구성이나 물리 페이지 복사량을 측정하지 않는다.

```python
import mmap
import tempfile

with tempfile.TemporaryFile() as f:
    f.write(b"ABCD")
    f.flush()
    with mmap.mmap(f.fileno(), 4, access=mmap.ACCESS_COPY) as private:
        private[0:1] = b"X"
        assert private[:] == b"XBCD"
        f.seek(0)
        assert f.read(4) == b"ABCD"
    with mmap.mmap(f.fileno(), 4, access=mmap.ACCESS_WRITE) as shared:
        shared[1:2] = b"Y"
        shared.flush()
    f.seek(0)
    assert f.read(4) == b"AYCD"
```

가상 로그 조회 서비스에서 파일을 mmap으로 조회한다면, 읽기 편의 외에 파일 교체·축소·오류 처리·메모리 압박을 설계해야 한다. 전체 파일을 RAM에 복사하는 초기 비용을 피했다고 이후 Fault 지연까지 사라지는 것은 아니다.

## 5. fork와 Copy-on-Write의 비용

Linux의 fork는 부모 주소 공간을 자식에게 복제하는 의미를 제공하면서 사적 메모리 페이지의 복사를 늦출 수 있다. 부모와 자식은 처음에 물리 페이지를 공유하고, 사적 페이지를 수정할 때 필요한 복사와 매핑 변경이 발생한다. 부모의 쓰기에도 적용된다. MAP_SHARED 영역의 공유 의미까지 사적 복사로 바뀌는 것은 아니다.

즉 fork가 무조건 메모리 전체를 즉시 복사하는 것도, 비용이 0인 것도 아니다. 페이지 테이블과 프로세스 관리 작업이 필요하며, 이후 얼마나 많은 페이지를 수정하는지에 따라 추가 할당·복사·Fault가 생긴다. 이미 단독 소유인 페이지 등에서는 모든 쓰기가 새 사본을 만든다고 단정하지 않는다.

가상 예로 페이지 크기를 4KiB라 가정하면 서로 다른 사적 페이지 10,000개를 새로 복사할 때 데이터 사본은 약 39.1MiB다. 실제 페이지 크기·공유 상태·Huge Page·할당 정책과 페이지 테이블 비용은 별도다. 작은 객체 하나씩 수정해도 서로 다른 많은 페이지를 건드리면 복사량이 커질 수 있다.

멀티스레드 프로세스의 fork는 메모리 최적화만의 문제가 아니다. 자식에는 호출 스레드만 남지만 다른 스레드가 잡았던 잠금 상태가 복제될 수 있어 exec 전의 안전한 함수 사용 규약을 지켜야 한다. Worker 생성 방식은 런타임 계약과 함께 정한다.

## 6. RSS를 합산하기 전에 무엇을 세는지 확인한다

| 지표 | 해석 | 주의 |
|---|---|---|
| 가상 매핑 크기 | 예약·매핑한 주소 범위 | 실제 상주량이 아님 |
| RSS | 프로세스의 상주 페이지 | 공유 페이지도 포함해 합산 중복 가능 |
| PSS | 공유 페이지 비용을 공유자 수에 따라 배분 | 순간 추정이며 전체 시스템 메모리와 동일하지 않음 |
| Private/Shared Dirty | 수정된 사적/공유 페이지 분류 | Dirty를 업무 영속화 완료로 해석하지 않음 |

Linux에서는 /proc/PID/smaps 같은 자료로 매핑별 RSS·PSS·Dirty를 함께 본다. 자식의 RSS가 부모와 비슷하다는 사실만으로 실제 RAM이 두 배 늘었다고 결론 내리지 않는다. 반대로 COW 이후 Private Dirty와 전체 메모리 압박이 커졌다면 쓰기 작업 집합과 공유가 깨진 범위를 조사한다.

