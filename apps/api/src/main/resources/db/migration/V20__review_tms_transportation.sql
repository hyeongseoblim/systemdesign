SET content_md = $tms_review$## 1. TMS의 범위와 사실의 소유자

TMS(Transportation Management System, 운송관리 시스템)는 출고된 화물을 어떤 경로·수단·시간창으로 움직일지 계획하고, 운송 작업·운임·추적 상태를 관리하는 시스템으로 설계할 수 있다. 다만 모든 제품이 같은 경계를 갖는 것은 아니다. OMS는 주문과 이행 의도를, WMS나 재고 서비스는 창고 작업과 재고를, 운송사·기사 앱·스캐너는 현장에서 관찰한 운송 이벤트를 소유할 수 있다.

| 관심사 | 가능한 책임 경계 | 먼저 정할 계약 |
| --- | --- | --- |
| 주문의 이행 의도 | OMS/커머스 서비스 | 주문·라인·Shipment 식별자, 취소 가능 시점 |
| 창고 작업과 출고 확정 | WMS/풀필먼트 | 피킹·패킹·선적 중 어떤 이벤트를 출고로 볼지 |
| 운송 계획과 배차 | TMS | Route·Vehicle·Leg 할당, 재계획 조건 |
| 현장 운송 사실 | 운송사·기사 앱·스캐너 | 이벤트 ID, 발생 시각, 시설·차량 식별자 |
| 고객에게 보여주는 추적 상태 | TMS의 투영 또는 별도 읽기 모델 | 상태 집계, 예외·정정 노출 규칙 |

`Shipment`라는 단어가 OMS와 TMS에 모두 등장해도 같은 객체라고 가정하지 않는다. OMS가 주문 라인의 이행 단위를 만들고 TMS가 그 단위에 `Waybill`, `Route`, `Leg`를 연결할 수 있다. 어느 시스템을 “단일 진실 원천”이라고 부를지는 전체 도메인이 아니라 각 사실의 종류별로 정한다. 예를 들어 TMS가 고객용 배송 상태의 투영을 소유하더라도, 집화·인수·배송완료의 원본 증거는 운송사나 현장 장치가 제공할 수 있다.

## 2. Waybill 상태와 이벤트 원장

운송장(Waybill)은 운송 단위의 식별자이고, 현재 상태는 운송 이벤트를 바탕으로 계산되는 투영일 수 있다. `isPickedUp`, `isDelivered`, `isReturned` 같은 Boolean을 독립적으로 늘리면 배송 완료와 반송이 동시에 참인 모순을 막기 어렵다. 상태 Enum과 허용 전이는 검증 지점을 만들지만, 중복 이벤트·동시 갱신·감사 기록까지 자동으로 해결하지는 않는다.

```mermaid
stateDiagram-v2
    [*] --> CREATED : WaybillIssued
    CREATED --> PICKED_UP : PickupScanned
    PICKED_UP --> IN_TRANSIT : DepartScanned
    IN_TRANSIT --> IN_TRANSIT : HubArrived / HubDeparted
    IN_TRANSIT --> OUT_FOR_DELIVERY : LastHubDeparted
    OUT_FOR_DELIVERY --> DELIVERED : DeliveryConfirmed
    OUT_FOR_DELIVERY --> DELIVERY_FAILED : DeliveryFailed
    DELIVERY_FAILED --> OUT_FOR_DELIVERY : ReAttempted
    DELIVERY_FAILED --> RETURNED : ReturnToSender
    DELIVERED --> [*]
    RETURNED --> [*]
```

`IN_TRANSIT`의 자기 전이는 현재 상태가 바뀌지 않는다는 뜻이지, 허브 입고·분류·허브 출고 기록을 버린다는 뜻이 아니다. 각 이벤트에는 최소한 `eventId`, `waybillId`, `eventType`, `facilityId`, `occurredAt`, `receivedAt`, `source`를 둔다. 같은 운송장이 여러 Leg를 지나면 `legId`나 출발·도착 시설을 함께 기록해야 “IN_TRANSIT 몇 번”을 실제 이동 구간으로 복원할 수 있다.

### 순서가 뒤바뀐 이벤트를 보정하는 방법

네트워크 지연 때문에 허브 출고 이벤트가 허브 입고 이벤트보다 먼저 서버에 도착할 수 있다. 단순히 수신 순서대로 상태를 바꾸면 늦게 도착한 과거 사실을 버리거나 이미 배송 완료된 건을 잘못 되돌릴 수 있다. 다음 층을 분리한다.

1. **중복 판정**: 장치가 만든 안정적인 `eventId`를 우선 키로 사용한다. `waybillId + scanType + occurredAt`만으로 합성하면 장치 시계 충돌·재스캔·시간 정밀도 차이를 구분하지 못할 수 있다.
2. **원본 보존**: `occurredAt`(현장 발생 시각)와 `receivedAt`(서버 수신 시각)을 분리해 원본 이벤트를 append-only로 보존한다. 수신 시각은 네트워크 상태의 관측값이지 운송 순서가 아니다.
3. **정렬 범위**: 같은 운송장 키를 Kafka 한 파티션에 모으면 소비자가 읽는 로그 순서는 안정화할 수 있지만, 오프라인 장치가 나중에 보낸 과거 이벤트까지 자동으로 시간순으로 만들어 주지는 않는다. 제한된 지연 구간(watermark/reorder window)을 둘지, 늦은 이벤트를 별도 보정 큐로 보낼지 정한다.
4. **투영 갱신**: 늦은 이벤트가 현재 상태와 모순되면 무조건 무시하지 않는다. 허용된 늦은 이벤트라면 이벤트 원장에서 해당 운송장 투영을 재계산하거나 보정 이벤트를 생성하고, 이미 고객에게 노출된 상태를 수정할 때는 감사·알림 정책을 적용한다.
5. **불법 전이와 정정 분리**: `DELIVERED → IN_TRANSIT` 같은 일반 전이를 열어두지 말고, 오배송 회수·오입력 정정은 별도의 correction/exception 흐름으로 기록한다.

## 3. 허브앤스포크와 P2P의 링크 수

허브앤스포크와 포인트투포인트(P2P)의 비교는 노선 수를 어떻게 세는지 먼저 밝혀야 한다. 아래 식은 양방향 이동을 하나의 무방향 링크로 보고, `N`을 배송 거점 수로 가정한다.

| 구조 | 링크 수(무방향, 단순 그래프) | 해석 |
| --- | ---: | --- |
| 중앙 허브 1개 + `N`개 스포크 | `N` | 각 스포크가 허브와 연결됨 |
| `N`개 거점의 완전 P2P | `N(N-1)/2` | 모든 거점 쌍이 직접 연결됨 |
| 방향별 운행을 별도 링크로 계산 | 위 값의 최대 2배 | 출발·도착 방향을 별도 노선으로 셈 |

따라서 “50개 거점”이 허브를 제외한 50개 스포크라는 가정이면 허브앤스포크는 50개, 완전 P2P는 `50×49/2 = 1,225`개 무방향 링크다. 50개에 허브가 이미 포함된 뜻이면 허브앤스포크는 49개다. 숫자 자체보다 노선 수와 물량 밀도의 가정을 함께 제시해야 한다.

| 관점 | 허브앤스포크 | P2P 직송 |
| --- | --- | --- |
| 적재 통합 | 여러 출발지를 묶어 만재를 만들기 쉬움 | 거점 쌍별 물량이 얇으면 반적재·공차 위험 |
| 리드타임 | 허브 환적·대기 구간이 추가될 수 있음 | 직송이면 경로와 인계가 짧음 |
| 장애 영향 | 허브·분류 설비 장애가 넓게 전파될 수 있음 | 장애가 특정 노선에 국한되기 쉬움 |
| 운영 복잡도 | 노선 수가 작고 표준화하기 쉬움 | 노선·차량·운임 계약이 빠르게 늘어남 |
| 적합한 조건 | 넓은 지역, 물량이 여러 거점에 분산, 높은 통합 효과 | 특정 거점 쌍의 물량·SLA가 충분하고 직송 제약이 적음 |

실제 네트워크는 순수한 한 형태보다 혼합형에 가깝다. 밀도가 높은 도심권은 직배하고 먼 지역은 허브를 거치거나, 단일 허브 장애를 줄이기 위해 여러 허브를 둔다. “허브가 항상 싸다” 또는 “직송이 항상 빠르다”가 아니라 차선별 물량, 환적 비용, 운송 약속, 장애 시 우회 가능성을 비교한다. 적재율·단가·처리량의 수치는 시설·상품·측정 기간이 확인되지 않으면 일반 사실로 제시하지 않는다.

## 4. Pickup·Line-haul·Feeder·Last-mile

한 Waybill의 이동은 여러 `Leg`로 나뉠 수 있다. 각 Leg가 계획·실행·예외 상태와 실제 시각을 가지면 “운송장이 이동 중”이라는 요약만으로 잃기 쉬운 병목을 보존할 수 있다.

| 구간 | 역할 | 확인할 이벤트 |
| --- | --- | --- |
| Pickup | 판매자·발송지에서 터미널로 집화 | 인수 스캔, 수량·포장 확인 |
| Line-haul | 터미널·허브 사이 장거리 이동 | 출발·도착, 차량·운송사 인계 |
| Feeder | 허브와 지역 터미널 사이 연결 | 분류 완료, 상차·하차 |
| Last-mile | 도착 터미널에서 수령지까지 배송 | 배송 출발, 실패 사유, 인수 증거 |

환적(cross-dock)은 입고 화물을 목적지별로 재분류해 다음 운송수단으로 넘기는 작업 방식이다. 보관을 최소화할 수 있지만, “보관하지 않는다”가 모든 시스템에서 보장되는 것은 아니다. 실제 출발 차수와 분류 처리량을 넘기면 허브 체류가 생기므로 `dwellTime`, 도크 대기, 분류 지연을 별도 지표로 기록한다.

## 5. 배차와 경로 최적화

배차는 화물·차량·기사·방문 순서를 연결하는 결정이다. 거리만 최소화하면 배송 약속이나 차량 적재 한도를 위반할 수 있으므로 다음 제약을 모델에 넣는다.

- 차량의 중량·부피·온도·위험물 수용 능력
- 기사 근무 시간, 휴게, 출발·복귀 위치
- 픽업 선행, 배송 시간창, 서비스 소요 시간
- 권역·운송사 계약·차량 호환성
- 도로·시설의 통행 제한과 재계획 시점

VRP(Vehicle Routing Problem)는 여러 차량이 제약을 만족하며 정류장을 방문하는 경로 문제다. 위치가 늘면 모든 후보 경로를 완전 탐색하기 어려워지므로, 실무 시스템은 초기 해·휴리스틱·메타휴리스틱·시간 제한을 조합해 짧은 시간에 충분히 좋은 해를 반환하고, 결과가 제약을 만족하는지 다시 검증한다. 최적화기가 실패하거나 늦어질 때 사용할 제한된 규칙 기반 fallback도 필요하다.

적재율 예시는 가정과 계산을 분리한다. 다른 조건이 같고 용량만 75%에서 90%로 개선된다면 필요한 용량 단위는 `0.75 / 0.90 = 0.833...`으로 이론상 약 16.7% 감소한다. 실제 차량 수는 시간창, 차량 종류, 기사 근무, 빈 차 회송 때문에 같은 비율로 줄지 않는다. 따라서 “적재율 1~2% 개선이 곧 이익” 같은 문장은 실제 비용·서비스 지표를 확인한 뒤에만 사용한다.

## 6. TrackingEvent 파이프라인

기사 앱과 허브 스캐너가 보내는 이벤트는 중복·지연·재전송될 수 있다. 이벤트 예시는 다음처럼 운송 사실과 서버 처리 정보를 나눈다.

```json
{
  "eventId": "scan-hub-a-9381",
  "waybillId": "W-42",
  "eventType": "HUB_DEPARTED",
  "facilityId": "HUB-A",
  "legId": "leg-2",
  "occurredAt": "2026-08-20T12:30:00Z",
  "receivedAt": "2026-08-20T13:02:11Z",
  "source": "driver-app"
}
```

### 중복·순서·오프라인 동기화

1. **중복**: producer 재시도와 장치 재전송을 구분한다. Kafka producer의 idempotence는 producer 재시도로 생기는 log 중복을 줄이는 기능이지, 서로 다른 장치가 같은 현장 사실을 보내는 경우나 DB·알림 부작용까지 deduplicate해 주는 기능은 아니다. 소비자도 `eventId` inbox/unique 제약과 멱등 상태 전이를 둔다.
2. **같은 운송장 순서**: `waybillId`를 Kafka key로 사용하면 같은 키의 레코드를 한 파티션에 모아 파티션 내부 순서를 활용할 수 있다. Kafka 토픽 전체의 전역 순서가 생기는 것은 아니며, 여러 producer·재시도·오프라인 이벤트의 사건 시각 순서를 별도 보정해야 한다.
3. **저장과 offset**: 외부 DB에 상태 투영을 쓰고 offset을 나중에 커밋하면 재처리될 수 있으므로 결과 쓰기를 멱등하게 한다. 같은 저장소에 결과와 처리 위치를 함께 기록하거나, Kafka transaction을 사용할 때도 외부 시스템까지 자동으로 원자화된다고 가정하지 않는다.
4. **지연 이벤트**: `occurredAt` 기준으로 제한된 재정렬 창을 두고, 창 밖의 늦은 이벤트는 보정 큐·재계산·수동 검토 중 정책을 선택한다. 고객에게 이미 보인 배송 완료를 조정할 때는 원본 이벤트와 정정 사유를 함께 남긴다.

```mermaid
flowchart LR
    A[기사 앱·허브 스캐너] --> B[Ingest API]
    B --> C{eventId 중복?}
    C -->|예| D[중복 결과 기록·종료]
    C -->|아니오| E[원본 이벤트 저장]
    E --> F[waybillId 키 토픽]
    F --> G[상태 투영]
    F --> H[고객 추적 읽기 모델]
    F --> I[ETA·알림·분석 소비자]
    E --> J{늦은 이벤트?}
    J -->|예| K[보정·재계산 큐]
```

소비자는 각각 독립 offset과 재처리 정책을 갖는다. 운영 지표에는 consumer lag, 중복률, 늦은 이벤트 비율, 보정 큐 적체, 상태 투영 지연, 고객 알림 재발송을 포함한다. “유실 없이 중복 없이 순서대로”를 한 설정으로 보장한다고 말하지 말고, producer·broker·consumer·외부 DB 각각의 보장을 나눠 설명한다.

## 7. 네트워크 선택을 검증하는 가상 설계

다음은 특정 회사의 내부 운영 사실이 아니라 설계 가설이다.

| 운영 조건 | 먼저 비교할 구조 | 검증할 데이터 |
| --- | --- | --- |
| 넓은 지역에 얇게 분산된 물량 | 허브 통합 | 차선별 물량, 환적 시간, 허브 처리량, 우회 경로 |
| 특정 도심권의 촘촘한 당일 약속 | 권역 직배 또는 소형 다중 허브 | 주문 밀도, 시간창, 기사 생산성, 실패 재방문 |
| 허브 장애가 큰 손실을 만드는 네트워크 | 다중 허브·우회 노선 | 장애 시 복구 시간, 여유 용량, 추가 운임 |
| 오프라인 장치가 많고 현장 재전송이 잦음 | 이벤트 원장 + 멱등 소비 | eventId 품질, late-event 비율, 보정 가능성 |

운송사 이름이나 특정 허브의 처리량을 예시로 들 때는 공개 자료가 해당 주장까지 확인하는지 따로 검증한다. 공개 근거가 없으면 회사의 내부 SLA·cut-off·적재율로 단정하지 않고, 위와 같은 가상 조건으로 표현한다.

## 면접에서 답할 때

먼저 OMS/WMS/TMS와 운송사·현장 장치의 사실 경계를 나눈다. 다음으로 Waybill의 현재 상태와 불변 TrackingEvent 원장을 구분하고, `eventId`, `occurredAt`, `receivedAt`, `legId`를 사용해 중복·지연·정정 흐름을 설명한다. 네트워크 질문에서는 링크 수의 가정과 물량 밀도·SLA·장애 전파를 비교한다. 마지막으로 배차의 제약·시간 제한·fallback과 Kafka의 파티션 내부 순서·at-least-once·외부 DB 멱등성을 함께 말한다.

> **면접 포인트**
>
> TMS의 핵심은 상태 이름을 많이 만드는 것이 아니다. 운송 사실을 이벤트 원장으로 보존하고, 그 위에 지연·중복·정정에 견디는 Waybill/Leg 투영과 배차 제약을 세우는 것이다.

